#!/usr/bin/env bash
# evals-auto-pr.sh — commit refreshed eval artifacts on a rolling bot branch
# and open (or update) an auto-PR. The evals-refresh workflow's counterpart to
# scripts/l10n-autofix.sh: same bot-commit identity, but where l10n-autofix
# self-heals a PR in place, scheduled eval refreshes have no PR to heal — so
# drift becomes a reviewable PR instead of a direct push to main.
#
# Usage:
#   scripts/evals-auto-pr.sh <branch> <title> -- <pathspec>...
#
#   <branch>    fixed bot branch for this artifact stream (e.g.
#               bot/evals-model-prices). Force-pushed on each refresh, so one
#               rolling PR carries the latest state instead of piling up weekly
#               siblings.
#   <title>     commit subject + PR title.
#   <pathspec>  the owned artifact paths; ONLY these are staged, so an
#               unrelated working-tree change can never ride along.
#
# No drift under the owned paths → exit 0 quietly. If an open PR already
# exists for the branch, the force-push updates it; otherwise `gh pr create`
# opens one. Extra context for the PR body can be piped in via the
# EVALS_PR_NOTE environment variable.
#
# Requires: gh (authenticated via GH_TOKEN/GITHUB_TOKEN), push rights on the
# repo. Note: pushes and PRs made with GITHUB_TOKEN do not trigger new
# workflow runs — the PR body says how to kick CI.
set -euo pipefail

if [[ $# -lt 4 ]]; then
  echo "usage: $0 <branch> <title> -- <pathspec>..." >&2
  exit 2
fi

branch=$1
title=$2
shift 2
if [[ ${1:-} != "--" ]]; then
  echo "usage: $0 <branch> <title> -- <pathspec>..." >&2
  exit 2
fi
shift
paths=("$@")

repo_root=$(git rev-parse --show-toplevel)
cd "$repo_root"

drift=0
if ! git diff --quiet -- "${paths[@]}"; then
  drift=1
fi
untracked=$(git ls-files --others --exclude-standard -- "${paths[@]}")
if [[ -n "$untracked" ]]; then
  drift=1
fi
if [[ $drift -eq 0 ]]; then
  echo "No drift under the owned paths; nothing to do."
  exit 0
fi

echo "Drift detected:"
git --no-pager diff --stat -- "${paths[@]}"
if [[ -n "$untracked" ]]; then
  printf 'New: %s\n' "$untracked"
fi

# Stage ONLY the owned paths and commit as the shared bot identity
# (l10n-autofix.sh convention).
git add -- "${paths[@]}"
if git diff --cached --quiet; then
  echo "Drift was not stageable under the owned paths; treating as fresh."
  exit 0
fi
# On a scheduled run the checkout is a detached HEAD; the PR base is the ref
# the workflow ran on (the default branch for cron), falling back to main.
base_ref="${GITHUB_REF_NAME:-$(git rev-parse --abbrev-ref HEAD)}"
if [[ "$base_ref" == "HEAD" ]]; then
  base_ref=main
fi
git -c user.name="github-actions[bot]" \
  -c user.email="41898282+github-actions[bot]@users.noreply.github.com" \
  commit --quiet \
  -m "$title" \
  -m "Auto-generated by the ${GITHUB_WORKFLOW:-evals-refresh} workflow (run ${GITHUB_RUN_ID:-local})."

git push --force origin "HEAD:refs/heads/${branch}"

# One rolling PR per stream: update the open one if it exists, else create it.
open_pr=$(gh pr list --head "$branch" --state open --json number --jq '.[0].number // empty' || true)
body="Automated refresh from the \`${GITHUB_WORKFLOW:-evals-refresh}\` workflow (run ${GITHUB_RUN_ID:-local}).

${EVALS_PR_NOTE:-}

> Opened with \`GITHUB_TOKEN\`, so CI does not start automatically — close and
> reopen the PR (or push any commit) to trigger the checks."
if [[ -n "$open_pr" ]]; then
  echo "Updated existing PR #${open_pr} via force-push to ${branch}."
  gh pr comment "$open_pr" --body "Refreshed by run ${GITHUB_RUN_ID:-local} (force-push)."
else
  gh pr create --head "$branch" --base "${base_ref}" --title "$title" --body "$body"
fi
# The local commit intentionally stays on the (detached) checkout — the job
# ends here; only the bot branch carries it remotely.
