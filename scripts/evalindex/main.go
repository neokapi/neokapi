// Command evalindex builds the data behind /evals: every eval kapi publishes,
// grouped by the layer it measures and the band that layer belongs to.
//
// It is a registry rather than a runner. Each eval has its own harness and its
// own cadence. Some regenerate on every build, some spend model calls, some
// drive an interactive agent and never run in CI at all; forcing them into one
// command would mean running the cheap ones rarely or the expensive ones
// constantly.
//
// What this adds is the thing no individual harness can: a view of what is
// measured, what is measured partially, and what is not measured at all. A gap a
// reader cannot see is a gap they will assume is covered.
//
//	go run ./scripts/evalindex                     # write the cover-page data
//	go run ./scripts/evalindex -out /dev/stdout    # inspect it
package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
	"time"
)

// DefaultOut is the committed data the cover page reads.
const DefaultOut = "web/src/pages/evals/_index.json"

// Total is every eval, counted once. Summing the named fields by hand was how
// the first version drifted: a status added to the registry has to be added to
// the sum too, and nothing said so.
func (c Coverage) Total() int {
	n := 0
	for _, v := range c.ByStatus {
		n += v
	}
	return n
}

func main() {
	out := flag.String("out", DefaultOut, "where to write the index")
	flag.Parse()

	index, err := Build()
	if err != nil {
		fmt.Fprintln(os.Stderr, "evalindex:", err)
		os.Exit(1)
	}
	data, err := Marshal(index)
	if err != nil {
		fmt.Fprintln(os.Stderr, "evalindex:", err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil && *out == DefaultOut {
		fmt.Fprintln(os.Stderr, "evalindex:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, data, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "evalindex:", err)
		os.Exit(1)
	}

	c := index.Coverage
	parts := make([]string, 0, len(AllStatuses))
	for _, st := range AllStatuses {
		if n := c.ByStatus[st]; n > 0 {
			parts = append(parts, fmt.Sprintf("%d %s", n, st))
		}
	}
	fmt.Printf("evalindex: %d bands, %d layers, %d evals (%s) → %s\n",
		len(index.Bands), len(index.Layers), len(index.Evals),
		strings.Join(parts, ", "), *out)
	if c.Undated > 0 {
		fmt.Printf("evalindex: %d dataset(s) carry no date, so their age cannot be shown\n", c.Undated)
	}
}

// Index is the whole cover page.
type Index struct {
	Note     string     `json:"_note"`
	Bands    []BandInfo `json:"bands"`
	Layers   []Layer    `json:"layers"`
	Evals    []Eval     `json:"evals"`
	Coverage Coverage   `json:"coverage"`
}

// Coverage is the honest summary: how much of the architecture is actually
// measured.
type Coverage struct {
	Measured    int `json:"measured"`
	Partial     int `json:"partial"`
	Unvalidated int `json:"unvalidated"`
	Blocked     int `json:"blocked"`
	Absent      int `json:"absent"`
	// ByStatus is the tally the named fields above are read from, and the one
	// thing that counts. The named fields exist because the page reads them by
	// name; they are derived here so the two can never disagree.
	ByStatus map[Status]int `json:"byStatus"`
	// LayersUnmeasured counts layers where no eval is measured or partial. It
	// is the number worth putting at the top of the page, because a layer with
	// nothing behind it is a hole in the architecture rather than a missing row.
	LayersUnmeasured int `json:"layersUnmeasured"`
	// PerBand counts evals by band, so a reader can see at a glance how much of
	// the evidence is deterministic and how much is sampled.
	PerBand map[string]int `json:"perBand"`
	// Undated counts datasets that cannot say how old they are. It is a
	// coverage problem in its own right: an old date can be judged and this
	// cannot.
	//
	// There is deliberately no Stale count here. Staleness depends on today,
	// and a count baked into a committed file would be wrong tomorrow. The page
	// computes it from each dataset's date.
	Undated int `json:"undated"`
}

const indexNote = "GENERATED by `go run ./scripts/evalindex`. The cards are authored; their claims about " +
	"coverage are checked against the repository by the companion tests, because a registry free to say " +
	"whatever it likes about how well kapi is measured would be the opposite of evidence."

// Build assembles the index and refuses to emit one that contradicts itself.
func Build() (*Index, error) {
	byID := make(map[string]Eval, len(evals))
	for _, e := range evals {
		if _, dup := byID[e.ID]; dup {
			return nil, fmt.Errorf("two evals share the id %q", e.ID)
		}
		byID[e.ID] = e
	}

	layerByID := make(map[string]Layer, len(layers))
	for _, l := range layers {
		if _, dup := layerByID[l.ID]; dup {
			return nil, fmt.Errorf("two layers share the id %q", l.ID)
		}
		layerByID[l.ID] = l
	}

	// Every band names layers that exist, in this band, each claimed once.
	claimedLayer := map[string]bool{}
	for _, b := range bands {
		if len(b.Layers) == 0 {
			return nil, fmt.Errorf("band %q lists no layers", b.ID)
		}
		for _, id := range b.Layers {
			l, ok := layerByID[id]
			if !ok {
				return nil, fmt.Errorf("band %q names layer %q, which does not exist", b.ID, id)
			}
			if l.Band != b.ID {
				return nil, fmt.Errorf("band %q claims layer %q, but that layer says it belongs to %q", b.ID, id, l.Band)
			}
			if claimedLayer[id] {
				return nil, fmt.Errorf("layer %q is claimed by two bands", id)
			}
			claimedLayer[id] = true
		}
	}
	for _, l := range layers {
		if !claimedLayer[l.ID] {
			return nil, fmt.Errorf("layer %q belongs to no band, so nothing on the page would render it", l.ID)
		}
	}

	// Every layer names evals that exist, each claimed exactly once. An eval in
	// two layers would be counted twice in every total on the page.
	claimedEval := map[string]bool{}
	for _, l := range layers {
		if len(l.Evals) == 0 {
			return nil, fmt.Errorf("layer %q lists no evals; an unmeasured layer still carries an absent card", l.ID)
		}
		for _, id := range l.Evals {
			if _, ok := byID[id]; !ok {
				return nil, fmt.Errorf("layer %q names eval %q, which has no card", l.ID, id)
			}
			if claimedEval[id] {
				return nil, fmt.Errorf("eval %q sits in two layers; give it a primary home", id)
			}
			claimedEval[id] = true
		}
	}
	for _, e := range evals {
		if !claimedEval[e.ID] {
			return nil, fmt.Errorf("eval %q sits in no layer, so nothing on the page would explain why it exists", e.ID)
		}
	}

	// Age is read from each dataset at build time, so the index cannot claim a
	// dataset is current when the file says otherwise.
	root, err := checkoutRoot()
	if err != nil {
		return nil, err
	}
	dated := make([]Eval, len(evals))
	copy(dated, evals)
	for i := range dated {
		if dated[i].Data == "" {
			continue
		}
		dated[i].Fresh = readFreshness(root, dated[i].Data)
		dated[i].Headline = readHeadline(root, dated[i].Data, dated[i].ID)
		byID[dated[i].ID] = dated[i]
	}

	index := &Index{Note: indexNote, Bands: bands, Layers: layers, Evals: dated}
	index.Coverage.PerBand = map[string]int{}
	// Counted through a map over AllStatuses rather than a switch. The switch
	// was the first version and it had no default, so adding StatusBlocked
	// dropped every blocked eval from the totals silently — the tally test
	// noticed, the code did not. A status missing from AllStatuses now panics
	// here instead.
	tally := map[Status]int{}
	for _, e := range dated {
		if !slices.Contains(AllStatuses, e.Status) {
			panic("evalindex: eval " + e.ID + " has status " + string(e.Status) + ", which is not in AllStatuses")
		}
		tally[e.Status]++
	}
	index.Coverage.ByStatus = tally
	index.Coverage.Measured = tally[StatusMeasured]
	index.Coverage.Partial = tally[StatusPartial]
	index.Coverage.Unvalidated = tally[StatusUnvalidated]
	index.Coverage.Blocked = tally[StatusBlocked]
	index.Coverage.Absent = tally[StatusAbsent]
	for _, e := range dated {
		if e.Fresh.Undated && e.Data != "" {
			index.Coverage.Undated++
		}
	}
	for _, l := range layers {
		index.Coverage.PerBand[string(l.Band)] += len(l.Evals)

		measured := false
		for _, id := range l.Evals {
			if s := byID[id].Status; s == StatusMeasured || s == StatusPartial {
				measured = true
			}
		}
		if !measured {
			index.Coverage.LayersUnmeasured++
		}
	}
	return index, nil
}

// Marshal renders the index as the exact bytes committed.
func Marshal(i *Index) ([]byte, error) {
	var b strings.Builder
	enc := json.NewEncoder(&b)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(i); err != nil {
		return nil, err
	}
	return []byte(b.String()), nil
}

// checkoutRoot locates the checkout so datasets can be read by their
// repo-relative paths from wherever the generator was invoked.
func checkoutRoot() (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, "git", "rev-parse", "--show-toplevel").Output()
	if err != nil {
		return "", fmt.Errorf("locating the repo root: %w", err)
	}
	return strings.TrimSpace(string(out)), nil
}
