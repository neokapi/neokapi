// The fixture: a documentation repository for an invented product, and the
// answer key it was written against, generated from one source.
//
// The product is Loomwise, a rota app for small hospitality and retail teams.
// Its help centre keeps eleven conventions nobody wrote down, and one habit it
// is inconsistent about. The key below declares them. The pages are prose
// written against the key: names enter the prose only through the key's own
// tokens, and every other convention is checked against the generated bytes
// before a cell is built, so the key and the pages cannot disagree. A page that
// used an avoided word, or a name spelt two ways, fails generation rather than
// producing a fixture that contradicts its own key.
//
// Nothing in the fixture mentions kapi, and the key never enters a cell.

// evalFixtureVersion is part of the fingerprint. Raise it when the meaning of
// the key changes without its bytes changing.
const evalFixtureVersion = "eval-v1"

// evalRepoName is the fixture repository's directory name, which becomes the
// project name `kapi init` writes into the recipe.
const evalRepoName = "loomwise-help"

// Convention categories, as the design names them.
const (
	evalCategoryName     = "name"
	evalCategorySpelling = "spelling"
	evalCategoryAvoided  = "avoided"
	evalCategoryHabit    = "habit"
	evalCategoryDecoy    = "decoy"
)

// EvalRule is one rule a person holds: the project never writes Term, and
// writes Use in its place.
type EvalRule struct {
	Term string `json:"term"`
	Use  string `json:"use"`
}

// EvalConvention is one planted convention, or the decoy.
type EvalConvention struct {
	ID       string `json:"id"`
	Category string `json:"category"`
	Summary  string `json:"summary"`
	// Rules are what a person loads for Measure 1, and what a recorded rule is
	// matched against for Measure 2. The decoy carries none: it must never
	// become a rule.
	Rules []EvalRule `json:"rules,omitempty"`
	// Cues are lowercase phrases only a statement about this convention would
	// use. An observation that carries one is about this convention.
	Cues []string `json:"cues,omitempty"`
	// Forms are the decoy's two spellings, each used roughly as often as the
	// other. Empty on every other convention.
	Forms [][]string `json:"forms,omitempty"`
	// Everywhere marks a habit that governs all prose, so it applies to every
	// piece of writing whatever its subject.
	Everywhere bool `json:"everywhere,omitempty"`
}

// terms lists the forms the project never writes.
func (c EvalConvention) terms() []string {
	out := []string{}
	for _, rule := range c.Rules {
		out = pairedUnique(out, rule.Term)
	}
	return out
}

// uses lists the forms the project writes instead.
func (c EvalConvention) uses() []string {
	out := []string{}
	for _, rule := range c.Rules {
		out = pairedUnique(out, rule.Use)
	}
	return out
}

// recalled reports whether a convention counts towards Measure 2's recall: the
// four names and the three spellings.
func (c EvalConvention) recalled() bool {
	return c.Category == evalCategoryName || c.Category == evalCategorySpelling
}

// EvalKey is the answer key: every convention the fixture plants, and the
// decoy.
type EvalKey struct {
	Version     string           `json:"version"`
	Product     string           `json:"product"`
	Conventions []EvalConvention `json:"conventions"`
}

// planted lists the eleven conventions, leaving out the decoy.
func (k EvalKey) planted() []EvalConvention {
	out := []EvalConvention{}
	for _, c := range k.Conventions {
		if c.Category != evalCategoryDecoy {
			out = append(out, c)
		}
	}
	return out
}

// decoy is the one convention the project is inconsistent about.
func (k EvalKey) decoy() EvalConvention {
	for _, c := range k.Conventions {
		if c.Category == evalCategoryDecoy {
			return c
		}
	}
	return EvalConvention{}
}

