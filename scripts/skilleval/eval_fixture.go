// The thresholds that make a convention discoverable from the content.
const (
	// A name or spelling appears at least this often, across this many files.
	evalMinUses  = 5
	evalMinFiles = 3
	// A word the project uses in place of an avoided one appears at least this
	// often, across this many files.
	evalMinReplacementUses  = 3
	evalMinReplacementFiles = 2
	// Each of the decoy's forms appears at least this often across this many
	// files, and the rarer form at least this share of the commoner.
	evalMinDecoyUses    = 4
	evalMinDecoyFiles   = 2
	evalMinDecoyBalance = 0.6
)

// EvalFixture is the generated repository and the key it was written against.
type EvalFixture struct {
	Files map[string][]byte `json:"-"`
	Key   EvalKey           `json:"key"`
	Tasks []EvalTask        `json:"tasks"`
}

// generateEvalFixture renders the pages and verifies them against the key. It
// is deterministic: nothing in it reads a clock, a random source or the
// environment, so it produces the same bytes on every run.
func generateEvalFixture() (EvalFixture, error) {
	replacer := strings.NewReplacer("{product}", evalProduct, "{feature}", evalFeature,
		"{free}", evalPlanFree, "{paid}", evalPlanPaid)
	fixture := EvalFixture{Files: map[string][]byte{}, Key: evalKey(), Tasks: evalTasks()}
	for name, page := range evalPages {
		fixture.Files[name] = []byte(replacer.Replace(page))
	}
	if problems := validateEvalFixture(fixture); len(problems) != 0 {
		return fixture, fmt.Errorf("the fixture contradicts its key: %s", strings.Join(problems, "; "))
	}
	return fixture, nil
}

// evalFileNames lists the fixture's files in a fixed order.
func (f EvalFixture) evalFileNames() []string {
	names := make([]string, 0, len(f.Files))
	for name := range f.Files {
		names = append(names, name)
	}
	slices.Sort(names)
	return names
}

// validateEvalFixture checks every property the design asks of the fixture,
// and returns one line per violation.
func validateEvalFixture(f EvalFixture) []string {
	problems := []string{}
	names := f.evalFileNames()
	for _, name := range names {
		if leftover := strings.Index(string(f.Files[name]), "{"); leftover >= 0 {
			problems = append(problems, fmt.Sprintf("%s holds an unreplaced token", name))
		}
		if strings.Contains(strings.ToLower(string(f.Files[name])), "kapi") {
			problems = append(problems, name+" mentions kapi")
		}
	}
	planted := f.Key.planted()
	if len(planted) != 11 || len(f.Key.Conventions) != 12 {
		problems = append(problems, fmt.Sprintf("the key holds %d entries with %d planted, not twelve with eleven", len(f.Key.Conventions), len(planted)))
	}
	counts := map[string]int{}
	for _, c := range planted {
		counts[c.Category]++
		for _, term := range c.terms() {
			if uses, _ := evalCorpusCount(f, term, true); uses != 0 {
				problems = append(problems, fmt.Sprintf("%s: the avoided form %q appears %d times", c.ID, term, uses))
			}
		}
		switch c.Category {
		case evalCategoryName, evalCategorySpelling:
			uses, files := evalCorpusCountAll(f, c.uses(), c.Category == evalCategorySpelling)
			if uses < evalMinUses || files < evalMinFiles {
				problems = append(problems, fmt.Sprintf("%s: used %d times in %d files, below %d in %d",
					c.ID, uses, files, evalMinUses, evalMinFiles))
			}
		case evalCategoryAvoided:
			uses, files := evalCorpusCountAll(f, c.uses(), true)
			if uses < evalMinReplacementUses || files < evalMinReplacementFiles {
				problems = append(problems, fmt.Sprintf("%s: the replacement is used %d times in %d files", c.ID, uses, files))
			}
		case evalCategoryHabit:
			if c.ID == "second-person" {
				for _, name := range names {
					if evalCount(string(f.Files[name]), "you", true) < 3 {
						problems = append(problems, name+" does not address the reader as you")
					}
				}
			}
		}
	}
	for category, want := range map[string]int{evalCategoryName: 4, evalCategorySpelling: 3, evalCategoryAvoided: 2, evalCategoryHabit: 2} {
		if counts[category] != want {
			problems = append(problems, fmt.Sprintf("the key plants %d %s conventions, not %d", counts[category], category, want))
		}
	}
	decoy := f.Key.decoy()
	if len(decoy.Forms) != 2 || len(decoy.Rules) != 0 {
		problems = append(problems, "the decoy needs exactly two forms and no rules")
	} else {
		first, firstFiles := evalCorpusCountAll(f, decoy.Forms[0], true)
		second, secondFiles := evalCorpusCountAll(f, decoy.Forms[1], true)
		low, high := min(first, second), max(first, second)
		switch {
		case low < evalMinDecoyUses || min(firstFiles, secondFiles) < evalMinDecoyFiles:
			problems = append(problems, fmt.Sprintf("the decoy's forms are used %d and %d times", first, second))
		case float64(low)/float64(high) < evalMinDecoyBalance:
			problems = append(problems, fmt.Sprintf("the decoy is used %d and %d times, which is not roughly even", first, second))
		}
	}
	for _, task := range f.Tasks {
		problems = append(problems, evalPromptProblems(f.Key, task)...)
	}
	return problems
}

// evalPromptWords are the words a prompt would use if it asked for the
// behaviour rather than measuring it.
var evalPromptWords = []string{"kapi", "context", "convention", "rule", "glossary", "terminology",
	"style guide", "voice", "spelling", "british", "check", "record"}

// evalPromptProblems keeps a prompt from handing the agent a convention: it may
// name neither the forms a convention avoids nor the forms it uses, except the
// habits, whose forms are ordinary words.
func evalPromptProblems(key EvalKey, task EvalTask) []string {
	problems := []string{}
	for _, word := range evalPromptWords {
		if evalCount(task.Prompt, word, true) != 0 {
			problems = append(problems, fmt.Sprintf("task %s mentions %q", task.ID, word))
		}
	}
	for _, c := range key.Conventions {
		forms := c.terms()
		if c.Category != evalCategoryHabit {
			forms = append(forms, c.uses()...)
		}
		for _, group := range c.Forms {
			forms = append(forms, group...)
		}
		for _, form := range forms {
			if evalCount(task.Prompt, form, true) != 0 {
				problems = append(problems, fmt.Sprintf("task %s names %q from %s", task.ID, form, c.ID))
			}
		}
	}
	return problems
}

// evalCorpusCount counts a form across the fixture, and the files it is in.
func evalCorpusCount(f EvalFixture, form string, fold bool) (uses, files int) {
	for _, name := range f.evalFileNames() {
		if n := evalCount(string(f.Files[name]), form, fold); n != 0 {
			uses += n
			files++
		}
	}
	return uses, files
}

// evalCorpusCountAll counts every form of a group together, and the files any
// of them is in.
func evalCorpusCountAll(f EvalFixture, forms []string, fold bool) (uses, files int) {
	for _, name := range f.evalFileNames() {
		inFile := 0
		for _, form := range forms {
			inFile += evalCount(string(f.Files[name]), form, fold)
		}
		if inFile != 0 {
			uses += inFile
			files++
		}
	}
	return uses, files
}

// evalCount counts whole-word occurrences of form in text. A form that starts
// or ends with a letter or digit must not continue a longer word on that side,
// so "user" is not found in "users" and "sign in" is not found in "sign-in".
// A form of punctuation, such as "!", is counted wherever it appears. With
// fold, case is ignored, which is how kapi matches a rule's term.
func evalCount(text, form string, fold bool) int {
	if form == "" {
		return 0
	}
	if fold {
		text, form = strings.ToLower(text), strings.ToLower(form)
	}
	first, _ := utf8.DecodeRuneInString(form)
	last, _ := utf8.DecodeLastRuneInString(form)
	count := 0
	for offset := 0; offset < len(text); {
		index := strings.Index(text[offset:], form)
		if index < 0 {
			break
		}
		start, end := offset+index, offset+index+len(form)
		before, _ := utf8.DecodeLastRuneInString(text[:start])
		after, _ := utf8.DecodeRuneInString(text[end:])
		if !(evalWordRune(first) && start > 0 && evalWordRune(before)) &&
			!(evalWordRune(last) && end < len(text) && evalWordRune(after)) {
			count++
		}
		offset = start + max(len(form), 1)
	}
	return count
}

func evalWordRune(r rune) bool { return unicode.IsLetter(r) || unicode.IsDigit(r) }

// evalFixtureHash binds resumed runs to the repository, the key and every
// prompt.
func evalFixtureHash(f EvalFixture) (string, error) {
	hash := sha256.New()
	encoder := json.NewEncoder(hash)
	if err := encoder.Encode(evalFixtureVersion); err != nil {
		return "", err
	}
	for _, name := range f.evalFileNames() {
		if err := encoder.Encode(struct {
			Name string
			Data []byte
		}{Name: name, Data: f.Files[name]}); err != nil {
			return "", err
		}
	}
	if err := encoder.Encode(struct {
		Key   EvalKey
		Tasks []EvalTask
	}{Key: f.Key, Tasks: f.Tasks}); err != nil {
		return "", err
	}
	return hex.EncodeToString(hash.Sum(nil)), nil
}

// materializeEvalRepo writes the fixture into an empty directory.
func materializeEvalRepo(dir string, f EvalFixture) error {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	root, err := openPairedRoot(dir)
	if err != nil {
		return err
	}
	defer root.Close()
	for _, name := range f.evalFileNames() {
		if err := root.MkdirAll(path.Dir(name), 0o700); err != nil {
			return err
		}
		if err := checkPairedPath(root, path.Dir(name)); err != nil {
			return err
		}
		file, err := root.OpenFile(name, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
		if err != nil {
			return fmt.Errorf("create fixture %q: %w", name, err)
		}
		_, writeErr := file.Write(f.Files[name])
		closeErr := file.Close()
		if writeErr != nil {
			return writeErr
		}
		if closeErr != nil {
			return closeErr
		}
	}
	return nil
}

// evalDiscoveryNames are the files a kapi or an agent host finds by walking up
// from a working directory. One of them above the fixture would bind the
// session to a project the evaluation is not measuring.
var evalDiscoveryNames = []string{"kapi.yaml", "CLAUDE.md", "AGENTS.md", ".mcp.json", ".kapi"}

// evalAncestorFindings reports every discoverable file above dir, which is what
// makes "outside the neokapi tree" a measured property rather than an
// assumption. An empty result is the passing one.
func evalAncestorFindings(dir string) ([]string, error) {
	resolved, err := filepath.EvalSymlinks(dir)
	if err != nil {
		return nil, err
	}
	findings := []string{}
	for current := filepath.Dir(resolved); ; current = filepath.Dir(current) {
		for _, name := range evalDiscoveryNames {
			if _, err := os.Lstat(filepath.Join(current, name)); err == nil {
				findings = append(findings, filepath.Join(current, name))
			}
		}
		parent := filepath.Dir(current)
		if parent == current {
			return findings, nil
		}
	}
}

// evalRecipeMapping completes the content mapping `kapi init` leaves for the
// person: the scaffolded recipe holds an empty collection list, and its own
// comments say to point collections at the files to keep in voice.
func evalRecipeMapping(recipe []byte) ([]byte, error) {
	const emptyCollections = "collections: []"
	body := string(recipe)
	if !strings.Contains(body, emptyCollections) {
		return nil, fmt.Errorf("scaffolded recipe no longer holds %q, so the fixture's content mapping was not written", emptyCollections)
	}
	mapping := "collections:\n" +
		"  - path: \"README.md\"\n    format: markdown\n" +
		"  - path: \"docs/**/*.md\"\n    format: markdown"
	body = strings.Replace(body, emptyCollections, mapping, 1)
	return []byte(body), nil
}
