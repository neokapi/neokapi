// reviewTypeNames maps each review-model struct to the TS name it renders as,
// so a field referring to one (History.prior, Judgement.findings) resolves to
// the interface this file emits rather than to the bare Go name.
var reviewTypeNames = func() map[reflect.Type]string {
	names := make(map[reflect.Type]string, len(reviewTypes))
	for _, e := range reviewTypes {
		names[e.typ] = e.name
	}
	return names
}()

// emitReview renders review.gen.ts as a string.
func emitReview() (string, error) {
	var b strings.Builder
	b.WriteString("// GENERATED by scripts/gen-contract-types. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with `make generate-contract-types`; the drift gate is\n")
	b.WriteString("// `make check-contract-types` (mirrors check-reference-docs).\n")
	b.WriteString("//\n")
	b.WriteString("// The review model (S-07), reflected from core/review and the structs it\n")
	b.WriteString("// carries (core/check, core/profile, core/state, core/model). Every review\n")
	b.WriteString("// client reads this shape: Kapi Desktop from the host, the platform's review\n")
	b.WriteString("// surfaces as the body of the REST review context, and the shared review\n")
	b.WriteString("// cards in @neokapi/ui-primitives as their props.\n\n")
	b.WriteString("import type { Anchor, Run } from \"./content.gen.ts\";\n")

	for _, e := range reviewTypes {
		iface, err := renderInterface(e)
		if err != nil {
			return "", fmt.Errorf("render %s: %w", e.name, err)
		}
		b.WriteString("\n")
		b.WriteString(iface)
	}
	return b.String(), nil
}
