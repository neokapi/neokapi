package comments

import (
	"bytes"
	"regexp"
	"sync"

	ts "github.com/tree-sitter/go-tree-sitter"
	tscs "github.com/tree-sitter/tree-sitter-c-sharp/bindings/go"

	"github.com/neokapi/neokapi/core/comment"
)

// csharpLanguages is C#. `///` lines and a `/** */` block directly before a
// declaration are its XML documentation, whose tags are placeholders.
func csharpLanguages() []*Language {
	return []*Language{{
		Name:        "csharp",
		DisplayName: "C#",
		Extensions:  []string{".cs"},
		// The doc marker comes first, so a comment line read through the
		// markers loses its whole opener.
		Markers: comment.Markers{Line: []string{"///", "//"}, Block: []comment.BlockMarker{{Open: "/*", Close: "*/"}}},
		grammar: tscs.Language,
		syntax:  csharpSyntax,
		once:    &sync.Once{},
		Canary: comment.Canary{
			Name:   "a C# documentation comment with a doubled word, below a ReSharper directive and above a string holding a comment marker",
			Source: []byte("// ReSharper disable once UnusedMember.Global\n/// <summary>Parses the the input.</summary>\npublic class Parser\n{\n    private string marker = \"// not a comment\";\n}\n"),
			Block:  "class/Parser",
		},
	}}
}

var csharpSyntax = &syntax{
	unit:       csharpUnit,
	directives: csharpDirectives,
	decl:       csharpDecl,
	container:  csharpContainer,
	markup:     true,
	// Roslyn treats a file whose leading comments hold <auto-generated> as
	// generated code.
	generated: regexp.MustCompile(`<auto-?generated\b`),
}

// csharpUnit classifies a C# comment node. As Roslyn reads them, `///` opens a
// documentation line unless it is `////`, a block that opens with `/**` is
// documentation unless it is `/**/`, and a line comment ends before its line
// break.
func csharpUnit(n *ts.Node, src []byte) (unit, bool) {
	if n.Kind() != "comment" {
		return unit{}, false
	}
	start, end := int(n.StartByte()), int(n.EndByte())
	text := src[start:end]
	if bytes.HasPrefix(text, []byte("//")) {
		for end > start && (src[end-1] == '\n' || src[end-1] == '\r') {
			end--
		}
		if bytes.HasPrefix(text, []byte("///")) && !bytes.HasPrefix(text, []byte("////")) {
			return unit{start: start, end: end, kind: kindDocLine, open: 3}, true
		}
		return unit{start: start, end: end, kind: kindLine, open: 2}, true
	}
	if bytes.HasPrefix(text, []byte("/**")) && end-start >= 5 {
		return unit{start: start, end: end, kind: kindDocBlock, open: 3, close: 2}, true
	}
	return unit{start: start, end: end, kind: kindBlock, open: 2, close: 2}, true
}

// csharpDirectives are the comments a C# tool reads: ReSharper's and Rider's
// inspection switches, the formatter switches they and CSharpier read, and
// Sonar's suppression.
var csharpDirectives = []directiveForm{
	regexpForm("resharper", "ReSharper", nil, regexp.MustCompile(`^ReSharper\s+(disable|restore|enable)\b`)),
	regexpForm("formatter", "@formatter", nil, regexp.MustCompile(`^@formatter:(on|off)\b`)),
	regexpForm("csharpier", "csharpier-ignore", nil, regexp.MustCompile(`^csharpier-ignore\b`)),
	{name: "nosonar", match: func(t commentText) (string, bool) { return "NOSONAR", nosonarMarker.MatchString(t.raw) }},
}

// csharpContainer reports the nodes whose direct children are declarations: a
// file, a namespace, a type declaration and its body, and an enum's members. A
// namespace adds nothing to a subject, so a file-scoped namespace and a braced
// one name their types alike.
func csharpContainer(kind, parent string) bool {
	switch kind {
	case "compilation_unit", "namespace_declaration", "class_declaration", "struct_declaration", "interface_declaration", "record_declaration", "enum_declaration":
		return true
	case "declaration_list":
		switch parent {
		case "namespace_declaration", "class_declaration", "struct_declaration", "interface_declaration", "record_declaration":
			return true
		}
	case "enum_member_declaration_list":
		return parent == "enum_declaration"
	}
	return false
}

// csharpDecl names a declaration: `class/Parser`, `struct/Pair`,
// `interface/IShape`, `record/Point`, `enum/Kind` or `delegate/Handler` for a
// type at any depth, and a member's own name for a method, constructor,
// property, event, field or enum member.
func csharpDecl(n *ts.Node, _ string, src []byte) (string, bool) {
	named := func(prefix string, name *ts.Node) (string, bool) {
		if name == nil {
			return "", false
		}
		return prefix + nodeName(name, src), true
	}
	switch n.Kind() {
	case "class_declaration":
		return named("class/", n.ChildByFieldName("name"))
	case "struct_declaration":
		return named("struct/", n.ChildByFieldName("name"))
	case "interface_declaration":
		return named("interface/", n.ChildByFieldName("name"))
	case "record_declaration":
		return named("record/", n.ChildByFieldName("name"))
	case "enum_declaration":
		return named("enum/", n.ChildByFieldName("name"))
	case "delegate_declaration":
		return named("delegate/", n.ChildByFieldName("name"))
	case "method_declaration", "constructor_declaration", "property_declaration", "event_declaration", "enum_member_declaration":
		return named("", n.ChildByFieldName("name"))
	case "indexer_declaration":
		return "this", true
	case "field_declaration", "event_field_declaration":
		for i := uint(0); i < n.NamedChildCount(); i++ {
			v := n.NamedChild(i)
			if v.Kind() != "variable_declaration" {
				continue
			}
			for j := uint(0); j < v.NamedChildCount(); j++ {
				if d := v.NamedChild(j); d.Kind() == "variable_declarator" {
					if name := d.ChildByFieldName("name"); name != nil {
						return named("", name)
					}
					return named("", d.NamedChild(0))
				}
			}
		}
	}
	return "", false
}
