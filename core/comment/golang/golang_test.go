func locateString(t *testing.T, name, src string) *comment.File {
	t.Helper()
	got, err := Provider{}.Locate(name, []byte(src))
	require.NoError(t, err)
	require.NoError(t, accountFor(name, []byte(src), got))
	return got
}

func TestDirectiveForms(t *testing.T) {
	for _, tc := range []struct {
		text string
		form string
	}{
		{"//go:build linux", "go:build"},
		{"//go:embed data", "go:embed"},
		{"//go:generate stringer -type=Kind", "go:generate"},
		{"//go:linkname local runtime.nanotime", "go:linkname"},
		{"//go:noinline", "go:noinline"},
		{"//go:nosplit", "go:nosplit"},
		{"//go:noescape", "go:noescape"},
		{"//go:uintptrescapes", "go:uintptrescapes"},
		{"//go:wasmimport env f", "go:wasmimport"},
		{"//go:debug panicnil=1", "go:debug"},
		{"// +build linux", "+build"},
		{"//line generated.go:10", "line"},
		{"/*line generated.go:10:1*/", "line"},
		{"//export Hello", "export"},
		{"//extern puts", "extern"},
		{"//sys\tread(fd int) (n int, err error)", "sys"},
		{"//sys read(fd int) (n int, err error)", "sys"},
		{"//sysnb\tgetpid() (pid int)", "sysnb"},
		{"//nolint", "nolint"},
		{"//nolint:errcheck // reason", "nolint:errcheck"},
		{"// nolint:errcheck", "nolint"},
		{"//lint:ignore SA1019 reason", "lint:ignore"},
		{"//lint:file-ignore U1000 reason", "lint:file-ignore"},
		{"//revive:disable-next-line:exported", "revive:disable-next-line:exported"},
		{"//gosec:disable G101", "gosec:disable"},
		{"// #nosec G101", "nosec"},
		{"// the #nosec marker here still suppresses", "nosec"},
		{"//todo:fix", "todo:fix"},
	} {
		t.Run(tc.text, func(t *testing.T) {
			form, ok := classifyDirective(tc.text, directiveForms)
			require.True(t, ok)
			assert.Equal(t, tc.form, form)
		})
	}

	for _, prose := range []string{
		"// Package demo is prose.",
		"// see https://go.dev/doc for more",
		"// nolintable is a word",
		"// sys is short for system",
		"//",
		"/* a block comment */",
		"// line 10 is where it happens",
		"// export the value",
		// Upper case is outside go/ast's directive shape.
		"//TODO:fix",
	} {
		t.Run("prose "+prose, func(t *testing.T) {
			_, ok := classifyDirective(prose, directiveForms)
			assert.False(t, ok)
		})
	}
}

func TestDirectiveFixtureCoversEveryForm(t *testing.T) {
	got := locateString(t, "directives.go", directiveFixture)
	for _, f := range directiveForms {
		matched := false
		for _, e := range got.Excluded {
			text := directiveFixture[e.Start:e.End]
			if form, ok := classifyDirective(text, []directiveForm{f}); ok && form != "" {
				matched = true
			}
		}
		assert.True(t, matched, "no line in the directive fixture exercises %q", f.name)
	}
}

