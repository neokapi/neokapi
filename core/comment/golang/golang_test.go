func TestGeneratedFileHasNoAddressableComment(t *testing.T) {
	got := locateString(t, "gen.go", "// Code generated by stringer. DO NOT EDIT.\n\npackage demo\n\n// Kind is a kind.\ntype Kind int\n")
	assert.Empty(t, got.Comments)
	require.Len(t, got.Excluded, 2)
	for _, e := range got.Excluded {
		assert.Equal(t, comment.ReasonGenerated, e.Reason)
	}
}

func TestCgoPreambleIsNotProse(t *testing.T) {
	for name, src := range map[string]string{
		"single import": "package demo\n\n// #include <stdio.h>\n// static int one() { return 1; }\nimport \"C\"\n\n// Two is prose.\nfunc Two() {}\n",
		"import group":  "package demo\n\nimport (\n\t// #include <stdio.h>\n\t\"C\"\n\t\"fmt\"\n)\n\n// Two is prose.\nfunc Two() { fmt.Println() }\n",
	} {
		t.Run(name, func(t *testing.T) {
			got := locateString(t, "cgo.go", src)
			require.Len(t, got.Comments, 1)
			assert.Equal(t, "Two is prose.", model.RunsText(got.Comments[0].Runs))
			for _, e := range got.Excluded {
				assert.Equal(t, comment.ReasonCgoPreamble, e.Reason)
			}
		})
	}
}

func TestExampleOutputIsNotProse(t *testing.T) {
	src := "package demo\n\nimport \"fmt\"\n\n// ExampleHello prints.\nfunc ExampleHello() {\n\t// Say it.\n\tfmt.Println(\"hi\")\n\t// Output:\n\t// hi\n}\n\n// Examplelower is not an example.\nfunc Examplelower() {\n\t// Output: kept\n}\n"
	got := locateString(t, "demo_test.go", src)
	var texts []string
	for _, c := range got.Comments {
		texts = append(texts, model.RunsText(c.Runs))
	}
	assert.Equal(t, []string{"ExampleHello prints.", "Say it.", "Examplelower is not an example.", "Output: kept"}, texts)
	var reasons []comment.Reason
	for _, e := range got.Excluded {
		reasons = append(reasons, e.Reason)
	}
	assert.Equal(t, []comment.Reason{comment.ReasonExampleOutput, comment.ReasonExampleOutput}, reasons)

	// The same function outside a test file is not an example go test runs.
	outside := locateString(t, "demo.go", src)
	assert.Len(t, outside.Comments, 5)
}

func TestLineDirectiveDoesNotShiftLines(t *testing.T) {
	src := "package demo\n\n//line other.go:100\nfunc a() {}\n\n// B is on line 6.\nfunc B() {}\n"
	got := locateString(t, "demo.go", src)
	require.Len(t, got.Comments, 1)
	assert.Equal(t, format.LineRange{First: 6, Last: 6}, got.Comments[0].Lines)
}

func TestBlankEdgesAreExcluded(t *testing.T) {
	src := "package demo\n\n//\n// Foo does things.\n//\n//go:noinline\nfunc Foo() {}\n"
	got := locateString(t, "demo.go", src)
	require.Len(t, got.Comments, 1)
	assert.Equal(t, "// Foo does things.", src[got.Comments[0].Start:got.Comments[0].End])
	var reasons []comment.Reason
	for _, e := range got.Excluded {
		reasons = append(reasons, e.Reason)
	}
	assert.Equal(t, []comment.Reason{comment.ReasonBlank, comment.ReasonBlank, comment.ReasonDirective}, reasons)
}

func TestDeprecatedIsRecorded(t *testing.T) {
	got := locateString(t, "demo.go", "package demo\n\n// Old does it.\n//\n// Deprecated: use New.\nfunc Old() {}\n\n// New does it.\nfunc New() {}\n")
	require.Len(t, got.Comments, 2)
	assert.True(t, got.Comments[0].Deprecated)
	assert.False(t, got.Comments[1].Deprecated)
}

func TestInteriorSyntaxIsProtected(t *testing.T) {
	src := `package demo

import "io"

// Copy copies from an [io.Reader] into a [Buffer], as [the Go site] explains.
//
// # Behaviour
//
// It reads until EOF:
//
//   - the first item
//   - the second item
//
// For example:
//
//	n, err := Copy(dst, src)
//
// See https://go.dev/doc for more.
//
// [the Go site]: https://go.dev
func Copy(r io.Reader) {}
`
	got := locateString(t, "demo.go", src)
	require.Len(t, got.Comments, 1)
	runs := got.Comments[0].Runs

	assert.Equal(t,
		"Copy copies from an  into a , as the Go site explains.\n\nBehaviour\n\nIt reads until EOF:\n\nthe first item\nthe second item\n\nFor example:\n\n\n\nSee  for more.\n\n",
		model.RunsText(runs), "only prose is text")

	var protected []string
	for _, r := range runs {
		switch {
		case r.Ph != nil:
			protected = append(protected, r.Ph.SubType+" "+r.Ph.Data)
		case r.PcOpen != nil:
			protected = append(protected, r.PcOpen.SubType+" "+r.PcOpen.Data+" "+r.PcOpen.Attr(model.AttrHref))
		case r.PcClose != nil:
			protected = append(protected, r.PcClose.SubType+" "+r.PcClose.Data)
		}
	}
	assert.Equal(t, []string{
		"go:doclink [io.Reader]",
		"go:doclink [Buffer]",
		"go:link [ https://go.dev",
		"go:link ]",
		"go:item -",
		"go:item -",
		"go:code n, err := Copy(dst, src)\n",
		"go:url https://go.dev/doc",
		"go:linkdef [the Go site]: https://go.dev",
	}, protected)
	for _, r := range runs {
		assert.True(t, r.Valid())
	}
}
